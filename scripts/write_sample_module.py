"""Write web/js/sample-data.js: the fictional sample as an ES module, so the
offline page can run the sample with no files dropped and no network.

Run: .venv/bin/python scripts/write_sample_module.py

The output is generated and git-ignored. It holds:
  SAMPLE          [{ name, text }]: roster.csv (from crosswalk.csv), schedule.csv,
                  and every inbox CSV named <date>/<file>
  SAMPLE_CLUB     the fictional club (synthetic, so its labels stay on)
  SAMPLE_EXAMPLE  { date, review }: the example review shown until the visitor saves their own
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "fictional"
EXAMPLE = ROOT / "web" / "examples" / "review-2026-09-20.json"
OUT = ROOT / "web" / "js" / "sample-data.js"


def sample_files() -> list[dict]:
    files = [
        {"name": "roster.csv", "text": (DATA / "crosswalk.csv").read_text(encoding="utf-8")},
        {"name": "schedule.csv", "text": (DATA / "schedule.csv").read_text(encoding="utf-8")},
    ]
    for day in sorted(p for p in (DATA / "inbox").iterdir() if p.is_dir()):
        for f in sorted(day.glob("*.csv")):
            files.append({"name": f"{day.name}/{f.name}", "text": f.read_text(encoding="utf-8")})
    return files


def main() -> None:
    club = json.loads((DATA / "club.json").read_text(encoding="utf-8"))
    example = {"date": EXAMPLE.stem.removeprefix("review-"),
               "review": json.loads(EXAMPLE.read_text(encoding="utf-8"))}
    dump = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    OUT.write_text(
        "// Generated by scripts/write_sample_module.py. Do not edit; not committed.\n"
        f"export const SAMPLE = {dump(sample_files())};\n"
        f"export const SAMPLE_CLUB = {dump({'name': club['name'], 'synthetic': True})};\n"
        f"export const SAMPLE_EXAMPLE = {dump(example)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
